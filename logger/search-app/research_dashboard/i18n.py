from .editor_i18n import EDITOR_TEXT

TEXT.update(WORKFLOW_TEXT)
TEXT.update(HISTORY_TEXT)
TEXT.update(EDITOR_TEXT)


def translate(key, language):
    pair = TEXT.get(key)
    return pair[1 if language == "it" else 0] if pair else key
